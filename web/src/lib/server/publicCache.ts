/* สั่งให้หน้าเว็บฝั่งลูกค้าสร้างใหม่หลังมีคนกดบันทึกในหลังบ้าน
 *
 * เด็ค Web 2026 ข้อ 20 · "ข้อมูลบริษัทไม่แสดงผลครับ" — /th /th/about /th/faq
 * /th/contact ถูกสร้าง HTML ไว้ล่วงหน้า และทั้งโปรเจกต์ไม่มี revalidatePath
 * อยู่สักที่ แก้ข้อมูลบริษัทแล้วหน้าเว็บจึงค้างอยู่แบบเดิมจนกว่าจะ deploy
 * รอบถัดไป ซึ่งไม่มีทางที่คนใช้งานจะเดาได้ว่าต้องรออะไร
 *
 * ใช้ 'layout' เพราะข้อมูลบริษัท โลโก้ ธีม และเมนู อยู่บน layout ร่วมกันทุกหน้า
 * ทุกภาษา — สั่งเฉพาะบางหน้าจะเหลือหน้าที่ยังค้างข้อมูลเก่าเสมอ
 *
 * หน้ายังเป็น static เหมือนเดิม ไม่ได้เปลี่ยนเป็น dynamic — แค่บอกว่าให้สร้าง
 * ใหม่ตอนมีคนกดบันทึก ความเร็วของผู้เข้าชมจึงไม่เปลี่ยน
 */
import { revalidatePath } from 'next/cache';

export function refreshPublicPages() {
  /* ห้ามให้การรีเฟรชแคชทำให้การบันทึกล้มเหลว — ข้อมูลลงฐานไปแล้ว
     ถ้าตรงนี้พังควรได้หน้าเก่าไปก่อน ดีกว่าคนใช้เห็นว่าบันทึกไม่สำเร็จ */
  try {
    /* '/[locale]' ต้องใส่วงเล็บเหลี่ยมตามชื่อโฟลเดอร์จริง — Next จับคู่ที่ไฟล์
       ไม่ใช่ที่ URL ถ้าส่ง '/th' หรือ '/' เฉย ๆ หน้าที่อยู่ใต้ [locale] จะไม่
       ถูกล้างเลย (เขียนเทสต์แล้วเห็นว่าเงียบ ๆ ไม่ทำอะไรจริง ๆ) */
    revalidatePath('/[locale]', 'layout');
    revalidatePath('/', 'layout');
    /* หน้าทรัพย์อยู่ลึกกว่านั้นหนึ่งชั้น และเป็น route ที่มีพารามิเตอร์
       การล้างที่ '/[locale]' แบบ layout ครอบหน้าที่เป็นลูกตรง ๆ (/th /th/about)
       แต่ไม่ครอบ /[locale]/property/[code] — ผลคือแก้ชื่อฟิลด์หรือปิดฟิลด์ใน
       Field Builder แล้วตารางรายละเอียดบนหน้าทรัพย์ยังขึ้นของเก่า ทั้งที่บันทึก
       สำเร็จ · อาการเดียวกับที่เคยเจอตอนแก้ลายน้ำแล้วรูปไม่เปลี่ยน */
    revalidatePath('/[locale]/property/[code]', 'page');
    revalidatePath('/[locale]/listing', 'page');
  } catch {
    /* ignore */
  }
}
